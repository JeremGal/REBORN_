// Renders 02-investigation/dossier.md: the human-readable rebuild dossier handed to block 3.
import fs from "node:fs";
import path from "node:path";
import { loadTarget } from "./load.mjs";
import { assertValidTarget } from "./validate.mjs";
import { assertNoLeak } from "./guard.mjs";
import { inputsDigest } from "./handoff.mjs";

const PRIO = { must: 0, should: 1, could: 2 };
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const list = (a) => (a && a.length ? a.join(", ") : "");
const count = (arr, key) => arr.reduce((m, x) => ((m[x[key]] = (m[x[key]] || 0) + 1), m), {});
const fmtCount = (o) => Object.entries(o).map(([k, v]) => `${k} ${v}`).join(", ") || "none";
const evSummary = (ev) => fmtCount(count(ev || [], "kind"));
const yamlish = (o) => Object.entries(o || {}).map(([k, v]) => `${k}=${typeof v === "object" ? JSON.stringify(v) : v}`).join(", ");

export function renderDossier(target) {
  assertValidTarget(target);
  const t = loadTarget(target);
  const m = t.meta || {};
  const title = m.kit_title ?? target;
  const ruleById = new Map(t.rules.map((r) => [r.id, r]));
  const screenById = new Map(t.screens.map((s) => [s.id, s]));
  const features = [...t.features].sort((a, b) => (PRIO[a.priority] ?? 9) - (PRIO[b.priority] ?? 9) || a.id.localeCompare(b.id));
  const openUnknowns = t.unknowns.filter((u) => u.status === "open");
  const L = [];
  const p = (...s) => L.push(...s);

  p(`# Rebuild dossier: ${title}`, "");
  p(`> Generated by \`node tools/reborn.mjs dossier ${target}\` from inputs \`${inputsDigest(t).slice(0, 16)}\` (the same cards always give the same dossier).`);
  p("> Source of truth: the YAML files next to this document. Do not edit this file by hand.");
  p("> Clean room: this dossier describes **behaviour**. It contains no original code, assets or branding.", "");

  p("## At a glance", "");
  p(`| | |`, `|---|---|`);
  p(`| Target | ${esc(title)} |`);
  p(`| Kind / platforms | ${esc(m.kind)} / ${esc(list(m.platforms))} |`);
  p(`| Domain | ${esc(m.domain)} |`);
  p(`| Versions studied | ${esc(list(m.versions))} |`);
  p(`| Technology | ${esc(m.tech?.stack ?? "unknown")}${m.tech?.status ? ` (${m.tech.status})` : ""} |`);
  p(`| Features | ${t.features.length}: ${fmtCount(count(t.features, "priority"))} / ${fmtCount(count(t.features, "status"))} |`);
  p(`| Rules, screens, entities | ${t.rules.length}, ${t.screens.length}, ${t.entities.length} |`);
  p(`| Open questions | ${openUnknowns.length} |`);
  p(`| Exploration | ${t.missions.length} missions, ${t.runs.length} runs, ${t.observations.length} observations |`);
  p(`| Evidence entries | ${t.evidence.length} |`, "");

  p("## Features", "");
  if (!features.length) p("_No feature card yet._", "");
  else {
    p("| ID | Feature | Module | Priority | Status | Confidence | Screens | Rules | Tests |", "|---|---|---|---|---|---|---|---|---|");
    for (const f of features) p(`| [${f.id}](#${f.id.toLowerCase()}) | ${esc(f.title)} | ${esc(f.module)} | ${f.priority} | ${f.status} | ${f.confidence} | ${list(f.screens)} | ${list(f.rules)} | ${(f.acceptance || []).length} |`);
    p("");
  }

  for (const f of features) {
    p(`### ${f.id}`, "", `**${f.title}** · ${f.module} · priority **${f.priority}** · ${f.status} (${f.confidence} confidence)`, "");
    p(`**Goal.** ${f.user_goal}`, "");
    if (f.actors?.length) p(`**Actors.** ${list(f.actors)}`, "");
    if (f.entry_points?.length) p(`**Entry points.** ${f.entry_points.map((e) => `${e.screen}${screenById.get(e.screen) ? ` (${screenById.get(e.screen).title})` : ""}${e.action ? `: ${e.action}` : ""}`).join("; ")}`, "");
    if (f.preconditions?.length) p("**Preconditions.**", ...f.preconditions.map((x) => `- ${x}`), "");
    if (f.inputs?.length) {
      p("**Inputs.**", "", "| Label | Field | Type | Required | Default | Validation |", "|---|---|---|---|---|---|");
      for (const i of f.inputs) p(`| ${esc(i.label)} | ${esc(i.field)} | ${esc(i.type)} | ${i.required ? "yes" : ""} | ${esc(i.default)} | ${esc(i.validation)} |`);
      p("");
    }
    p("**Steps.**", ...f.steps.map((s) => `${s.n}. _${s.actor}_: ${s.does}${s.screen ? ` [${s.screen}]` : ""}${s.rules?.length ? ` (${s.rules.join(", ")})` : ""}`), "");
    if (f.rules?.length) {
      p("**Business rules applied.**");
      for (const id of f.rules) { const r = ruleById.get(id); p(`- **${id}** ${r ? `${r.title}: ${r.statement}${r.formula ? ` \`${r.formula}\`` : ""}` : "(missing rule card)"}`); }
      p("");
    }
    if (f.outputs?.length) p("**Outputs.**", ...f.outputs.map((o) => `- _${o.kind}_: ${o.description}${o.entities?.length ? ` (${o.entities.join(", ")})` : ""}${o.format ? `. Format: ${o.format}` : ""}`), "");
    if (f.errors?.length) p("**Errors and edge cases.**", ...f.errors.map((e) => `- When ${e.when}: ${e.behaviour}${e.message ? ` Message: "${e.message}"` : ""}`), "");
    p("**Acceptance scenarios.**");
    for (const a of f.acceptance) p(`- **${a.id}** Given ${a.given}; when ${a.when}; then ${a.then}.${a.expected_values ? ` Expected: ${yamlish(a.expected_values)}.` : ""}${a.source_run ? ` (observed in ${a.source_run})` : ""}`);
    p("");
    if (f.rebuild_notes) p("**Rebuild notes.**", "", f.rebuild_notes.trim(), "");
    p(`**Evidence.** ${evSummary(f.evidence)}: ${(f.evidence || []).map((e) => `\`${e.ref.length > 24 ? `${e.ref.slice(0, 22)}...` : e.ref}\``).join(", ")}`, "");
    if (f.unknowns?.length) p(`**Open questions.** ${f.unknowns.join(", ")}`, "");
  }

  p("## Business rules", "");
  if (!t.rules.length) p("_No rule card yet._", "");
  for (const r of [...t.rules].sort((a, b) => a.id.localeCompare(b.id))) {
    p(`### ${r.id} ${r.title}`, "", `_${r.kind}_ · ${r.status} (${r.confidence}) · evidence: ${evSummary(r.evidence)}`, "", r.statement, "");
    if (r.formula) p("```text", r.formula, "```", "");
    if (r.applies_to?.length) p(`Applies to: ${list(r.applies_to)}`, "");
    if (r.examples?.length) {
      p("| Given | Expect | Source |", "|---|---|---|");
      for (const x of r.examples) p(`| ${esc(yamlish(x.given))} | ${esc(yamlish(x.expect))} | ${esc(x.source?.ref ?? "")} |`);
      p("");
    }
    if (r.contradictions?.length) p("Contradictions:", ...r.contradictions.map((c) => `- ${c}`), "");
  }

  p("## Data model", "");
  if (!t.entities.length) p("_No entity yet._", "");
  const rel = { "one-to-many": "||--o{", "many-to-one": "}o--||", "one-to-one": "||--||", "many-to-many": "}o--o{" };
  const edges = t.entities.flatMap((e) => (e.relations || []).map((r) => `  ${e.name} ${rel[r.kind]} ${r.to} : "${(r.via || r.description || "").replace(/"/g, "'")}"`));
  if (edges.length) p("```mermaid", "erDiagram", ...edges, "```", "");
  for (const e of t.entities) {
    p(`### ${e.name}`, "", `${e.description} · ${e.status}${e.storage?.engine ? ` · storage: ${e.storage.engine}${e.storage.observed_table ? ` (${e.storage.observed_table})` : ""}` : ""}`, "");
    p("| Field | Label | Type | Required | Details |", "|---|---|---|---|---|");
    for (const f of e.fields) {
      const details = [f.unique && "unique", f.max_length && `max ${f.max_length}`, f.precision !== undefined && `${f.precision} decimals`, f.enum_values && `values: ${f.enum_values.join(" / ")}`, f.ref && `→ ${f.ref}`, f.default !== undefined && `default ${f.default}`, f.computed_by && `computed by ${f.computed_by}`].filter(Boolean).join("; ");
      p(`| ${f.name} | ${esc(f.label)} | ${f.type} | ${f.required ? "yes" : ""} | ${esc(details)} |`);
    }
    if (e.lifecycle?.length) p("", `Lifecycle: ${e.lifecycle.join(" → ")}`);
    p("");
  }

  p("## Screens", "");
  if (!t.screens.length) p("_No screen yet._", "");
  const nav = t.screens.flatMap((s) => (s.actions || []).filter((a) => a.navigates_to).map((a) => `  ${s.id.replace("-", "")}["${s.id} ${s.title.replace(/"/g, "'")}"] -->|${a.label.replace(/[|"]/g, " ")}| ${a.navigates_to.replace("-", "")}`));
  if (nav.length) p("```mermaid", "flowchart LR", ...nav, "```", "");
  for (const s of [...t.screens].sort((a, b) => a.id.localeCompare(b.id))) {
    p(`### ${s.id} ${s.title}`, "", `_${s.kind}_ · ${s.status} · ${s.purpose}`, "");
    if (s.layout) p(`Layout: ${s.layout}`, "");
    if (s.fields?.length) { p("| Label | Control | Binds | Required | Validation |", "|---|---|---|---|---|"); for (const f of s.fields) p(`| ${esc(f.label)} | ${f.control} | ${esc(f.binds)} | ${f.required ? "yes" : ""} | ${esc(f.validation)}${f.columns ? ` Columns: ${esc(f.columns.join(", "))}` : ""} |`); p(""); }
    if (s.actions?.length) p("Actions:", ...s.actions.map((a) => `- ${a.label}${a.shortcut ? ` (${a.shortcut})` : ""}${a.triggers ? ` → ${a.triggers}` : ""}${a.navigates_to ? ` → ${a.navigates_to}` : ""}`), "");
    if (s.screenshots?.length) p(...s.screenshots.map((x) => `![${s.id}](../${x})`), "");
  }

  p("## Open questions", "");
  if (!openUnknowns.length) p("_None._", "");
  else {
    p("| ID | Question | Why it matters | Blocks | Probe |", "|---|---|---|---|---|");
    for (const u of openUnknowns) p(`| ${u.id} | ${esc(u.question)} | ${esc(u.why)} | ${list(u.blocks)} | ${u.probe ? `${u.probe.kind}: ${esc(u.probe.suggestion)}` : ""} |`);
    p("");
  }

  p("## Traceability", "", "| Feature | Rules | Screens | Entities | Evidence | Tests |", "|---|---|---|---|---|---|");
  for (const f of features) p(`| ${f.id} | ${list(f.rules)} | ${list(f.screens)} | ${list(f.entities)} | ${evSummary(f.evidence)} | ${(f.acceptance || []).map((a) => a.id).join(", ")} |`);
  p("");

  p("## Evidence register", "", `${t.evidence.length} entries in \`evidence/index.yaml\` (raw files stay in the investigator's local evidence store, never in git).`, "");
  const byOp = count(t.evidence.map((e) => ({ k: `${e.tool} ${e.operation}` })), "k");
  if (Object.keys(byOp).length) { p("| Tool / operation | Count |", "|---|---|"); for (const [k, v] of Object.entries(byOp)) p(`| ${esc(k)} | ${v} |`); p(""); }

  const text = L.join("\n");
  assertNoLeak(target, text, "the dossier", t.entities);
  const out = path.join(t.root, "02-investigation", "dossier.md");
  fs.writeFileSync(out, text);
  return out;
}
